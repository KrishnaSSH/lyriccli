class Song:
    def __init__(
        self, file_name, title, artist, album_name, album_artist, genre, song_duration
    ):
        self.file_name = file_name
        self.title = title
        self.album_name = album_name
        self.artist = artist
        self.album_artist = album_artist
        self.genre = genre
        self.song_duration = song_duration
